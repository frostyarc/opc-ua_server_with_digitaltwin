# =====================================================================
# 문제 1. 엣지감지 — "False에서 True로 막 바뀐 순간"만 잡아내기
# =====================================================================
# 설명: readings는 1초마다 측정한 값입니다. 계속 True인 동안엔 반응하지 않고,
#       "방금 막 False에서 True로 바뀐 그 순간"에만 "엣지 감지!"를 출력해야 합니다.

readings = [False, False, True, True, True, False, True, True]

prev = False

for value in readings:
    if value and not prev:                       # ✍️ value와 prev를 이용한 조건으로 바꾸세요
        print("엣지 감지!")

    prev = value            # ✍️ 다음 바퀴를 위해 prev를 뭘로 바꿔야 할지 쓰세요


# =====================================================================
# 문제 2. 대기줄 처리 — pop / append
# =====================================================================
# 설명: orders_pending 맨 앞 사람을 꺼내서 next_order에 담고,
#       그 사람을 orders_in_flight 맨 뒤에 넣어야 합니다.

orders_pending = [101, 102, 103]
orders_in_flight = []

next_order = orders_pending.pop(0)                  # ✍️ 맨 앞 걸 "꺼내면서 동시에 목록에서 제거"하는 메서드 1개

orders_in_flight.append(next_order)                                # ✍️ next_order를 orders_in_flight 맨 뒤에 추가

print(next_order, orders_pending, orders_in_flight)


# =====================================================================
# 문제 3. 파이프라인 자리 이동 — 하부칸 -> 암칸으로 주문 넘기기
# =====================================================================
# 설명: 하부칸(STAGE_UNDER)에 있던 주문을 암칸(STAGE_ARM)으로 옮기고,
#       하부칸은 빈 자리(None)로 만드세요. 순서 중요!

STAGE_UNDER, STAGE_ARM = 0, 1
stage_orders = [101, None]

stage_orders[STAGE_ARM] = stage_orders[STAGE_UNDER]                                # ✍️ 암칸에 하부칸 값을 복사
stage_orders[STAGE_UNDER] = None                              # ✍️ 하부칸을 None으로 비우기

print(stage_orders)


